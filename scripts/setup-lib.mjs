import { open, lstat, unlink } from 'node:fs/promises';
import { join } from 'node:path';
import { parsePublicOrigin } from '../src/server/originPolicy.ts';

// Single quotes are literal in both Node and Compose. Do not use shell escapes:
// their apostrophe/backslash rules differ between these environment parsers.
const literal = (value) => {
  if (typeof value !== 'string' || /['\x00-\x1f\x7f]/u.test(value)) throw new Error('Invalid setup configuration encoding');
  // Compose interprets an odd trailing backslash as escaping the closing quote.
  if ((value.match(/\\+$/u)?.[0].length ?? 0) % 2 !== 0) throw new Error('Invalid setup configuration encoding');
  return `'${value}'`;
};

/** Inputs and injected cryptographic functions stay in memory; this module never logs. */
export async function createSetupFile({ directory, input, hashPassword, randomBytes }) {
  if (!input || !['local', 'public'].includes(input.mode)) throw new Error('Invalid setup mode');
  let origin;
  try { origin = parsePublicOrigin(input.origin, input.mode); } catch { throw new Error('Invalid setup origin'); }
  if (typeof input.adminName !== 'string' || !input.adminName.trim() || input.adminName.length > 128) throw new Error('Invalid setup administrator name');
  literal(input.adminName);
  if (typeof input.password !== 'string' || [...input.password].length < 12 || Buffer.byteLength(input.password, 'utf8') > 1024) throw new Error('Invalid setup password length');
  if (input.password !== input.confirmation) throw new Error('Invalid setup password confirmation');

  let contents;
  try {
    const databasePassword = randomBytes(32).toString('hex');
    const sessionSecret = randomBytes(32).toString('hex');
    if (!/^[a-f0-9]{64}$/.test(databasePassword) || !/^[a-f0-9]{64}$/.test(sessionSecret)) throw new Error();
    const passwordHash = await hashPassword(input.password);
    if (!passwordHash.startsWith('$argon2id$')) throw new Error();
    const settings = {
      NODE_ENV: 'production', DEPLOYMENT_MODE: input.mode, PORT: '3000',
      POSTGRES_USER: 'agentfiles', POSTGRES_DB: 'agentfiles', POSTGRES_PASSWORD: databasePassword,
      DATABASE_URL: `postgresql://agentfiles:${databasePassword}@db:5432/agentfiles`,
      STORAGE_ROOT: '/data/storage', SESSION_SECRET: sessionSecret,
      ADMIN_USERNAME: input.adminName, ADMIN_PASSWORD_HASH: passwordHash, PUBLIC_BASE_URL: origin,
      TRUST_PROXY: '', RETENTION_DAYS: '7', ALLOW_PERSISTENT_FILES: 'false', FILE_ISSUANCE_ENABLED: 'true',
      MAX_UPLOAD_BYTES: '1073741824', MAX_STORAGE_BYTES: '10737418240', MIN_FREE_DISK_BYTES: '1073741824',
      MAX_CONCURRENT_UPLOADS: '4', CLEANUP_INTERVAL_SECONDS: '3600', ORPHAN_GRACE_SECONDS: '86400',
      CLEANUP_BATCH_SIZE: '100', METADATA_RETENTION_DAYS: '30', EVENT_RETENTION_DAYS: '30', APP_PORT: '3000',
    };
    contents = '# Generated by AgentFiles setup. Keep this file private.\n' + Object.entries(settings).map(([key, value]) => `${key}=${literal(value)}\n`).join('');
  } catch { throw new Error('Unable to prepare setup configuration'); }

  const path = join(directory, '.env');
  let file, identity;
  try {
    file = await open(path, 'wx', 0o600);
    identity = await file.stat();
    await file.writeFile(contents, 'utf8');
    await file.sync();
    await file.close();
  } catch (error) {
    if (file) {
      await file.close().catch(() => {});
      // Never delete an existing file, or a replacement created by another actor.
      if (identity) {
        const current = await lstat(path).catch(() => undefined);
        if (current?.dev === identity.dev && current?.ino === identity.ino) await unlink(path).catch(() => {});
      }
    }
    if (!file && error?.code === 'EEXIST') throw new Error('Setup configuration already exists');
    throw new Error('Unable to write setup configuration');
  }
}
